let lang = localStorage.getItem("emjm-lang") || "fr";

function applyLang(l) {
  lang = l;
  localStorage.setItem("emjm-lang", l);
  document.documentElement.lang = l;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    const val = I18N[l][key];
    if (val !== undefined) el.innerHTML = val;
  });
  document.getElementById("langToggle").textContent = l === "fr" ? "EN" : "FR";
  document.title = l === "fr"
    ? "Électromécanique JM — Électromécanique automobile à Lévis | Électricité et mécanique auto"
    : "Électromécanique JM — Auto Electrical in Lévis | Auto Electrical and Mechanical";
}

document.getElementById("langToggle").addEventListener("click", () => {
  applyLang(lang === "fr" ? "en" : "fr");
});

const menuBtn = document.getElementById("menuBtn");
const mainNav = document.getElementById("mainNav");
menuBtn.addEventListener("click", () => mainNav.classList.toggle("open"));
mainNav.querySelectorAll("a").forEach(a => a.addEventListener("click", () => mainNav.classList.remove("open")));

applyLang(lang);
